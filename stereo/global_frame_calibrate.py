#!/usr/bin/env python3
"""
Calibrate a global coordinate frame attached to an LED calibration board.

Coordinate systems:
    {0} = Global LED-board coordinate system.
    {A} = Camera 1 coordinate system.

The stereo calibration is assumed to have already been solved by
stereo/stereo_calibrate.py:

    P1 = K1 [I | 0]
    P2 = K2 [R_stereo | T_stereo]

The LED board is observed simultaneously by both cameras.

This script:
    1. Triangulates the LED points into Camera 1 coordinates.
    2. Uses the known LED-board geometry to estimate the rigid transform
       from the LED-board frame {0} to Camera 1 frame {A}.
    3. Inverts that transform to obtain Camera 1 -> Global LED frame.
    4. Saves the transform and calibration metadata to JSON.

The resulting transform can be used as:

    P_global = R_A_to_0 @ P_camera1 + T_A_to_0

where P_camera1 is any 3D point produced by stereo triangulation.

Usage:

    python stereo/global_frame_calibrate.py \
        track_logs/stereo/img_points.npz \
        intrinsic/output/camera_1_intrinsics.json \
        intrinsic/output/camera_2_intrinsics.json \
        track_logs/stereo/stereo_calibration.json \
        --spacing-x 25 \
        --spacing-y 25 \
        --columns 4 \
        --rows 6 \
        --output track_logs/stereo/global_frame_calibration.json

Important:
    The spacing and LED geometry must use the same convention as the
    stereo calibration.

    The global LED frame is defined as:
        origin = LED with zero-based grid index 0
        +X = increasing column direction
        +Y = increasing row direction
        +Z = board normal determined by the right-hand rule.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import cv2
import numpy as np


# =====================================================================
# STAGE 1 - LED board geometry
# =====================================================================


def make_led_box_geometry(
    spacing_x: float,
    spacing_y: float,
    columns: int,
    rows: int,
    h5_id_for_led1: int = 0,
) -> dict[int, np.ndarray]:
    """
    Build the known 3D geometry of the LED board.

    Coordinates are expressed in the global LED-board frame {0}:

        origin = first LED
        +X = column direction
        +Y = row direction
        Z  = 0 for all LEDs

    Returns:
        beacon_id -> (3,) float32 coordinate
    """
    points: dict[int, np.ndarray] = {}

    for zero_based_led in range(columns * rows):
        row, column = divmod(zero_based_led, columns)
        beacon_id = h5_id_for_led1 + zero_based_led

        points[beacon_id] = np.array(
            [
                column * spacing_x,
                row * spacing_y,
                0.0,
            ],
            dtype=np.float32,
        )

    return points


# =====================================================================
# STAGE 2 - Load calibration data
# =====================================================================


def load_intrinsics(
    path: Path,
) -> tuple[np.ndarray, np.ndarray, tuple[int, int]]:
    """Load camera intrinsics generated by intrinsic calibration."""
    data = json.loads(path.read_text())

    camera_matrix = np.asarray(
        data["camera_matrix"],
        dtype=np.float64,
    )

    distortion = np.asarray(
        data["distortion_coefficients"],
        dtype=np.float64,
    )

    width, height = data["image_size"]

    return camera_matrix, distortion, (width, height)


def load_stereo_calibration(
    path: Path,
) -> dict:
    """Load stereo R/T from stereo_calibrate.py output."""
    data = json.loads(path.read_text())

    R = np.asarray(data["R"], dtype=np.float64)
    T = np.asarray(data["T"], dtype=np.float64).reshape(3, 1)

    return {
        "R": R,
        "T": T,
        "data": data,
    }


# =====================================================================
# STAGE 3 - Triangulation
# =====================================================================


def build_projection_matrices(
    camera_matrix_1: np.ndarray,
    camera_matrix_2: np.ndarray,
    R: np.ndarray,
    T: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Build projection matrices using Camera 1 as the reference frame.

        P1 = K1 [I | 0]
        P2 = K2 [R | T]

    Therefore triangulated points are expressed in Camera 1 coordinates.
    """
    Rt1 = np.hstack(
        [
            np.eye(3, dtype=np.float64),
            np.zeros((3, 1), dtype=np.float64),
        ]
    )

    Rt2 = np.hstack([R, T])

    P1 = camera_matrix_1 @ Rt1
    P2 = camera_matrix_2 @ Rt2

    return P1, P2


def triangulate_points(
    P1: np.ndarray,
    P2: np.ndarray,
    points1: np.ndarray,
    points2: np.ndarray,
) -> np.ndarray:
    """
    Triangulate corresponding pixels.

    Args:
        points1: (N, 2)
        points2: (N, 2)

    Returns:
        points3d: (N, 3), expressed in Camera 1 coordinates.
    """
    points1 = np.asarray(points1, dtype=np.float64)
    points2 = np.asarray(points2, dtype=np.float64)

    points_4d = cv2.triangulatePoints(
        P1,
        P2,
        points1.T,
        points2.T,
    )

    w = points_4d[3]

    if np.any(np.abs(w) < 1e-12):
        raise ValueError(
            "Triangulation produced points with near-zero homogeneous "
            "coordinate."
        )

    points_3d = (points_4d[:3] / w).T

    return points_3d


# =====================================================================
# STAGE 4 - Rigid 3D transform
# =====================================================================


def estimate_rigid_transform(
    source_points: np.ndarray,
    target_points: np.ndarray,
) -> tuple[np.ndarray, np.ndarray, float]:
    """
    Estimate rigid transform:

        target = R @ source + T

    using the Kabsch algorithm.

    Args:
        source_points:
            Points in source coordinate system, shape (N, 3).

        target_points:
            Corresponding points in target coordinate system, shape (N, 3).

    Returns:
        R:
            3x3 rotation matrix.
        T:
            3x1 translation vector.
        rms:
            RMS point-to-point fitting error.
    """
    source = np.asarray(source_points, dtype=np.float64)
    target = np.asarray(target_points, dtype=np.float64)

    if source.shape != target.shape:
        raise ValueError(
            f"Source/target shape mismatch: "
            f"{source.shape} vs {target.shape}"
        )

    if source.ndim != 2 or source.shape[1] != 3:
        raise ValueError(
            f"Expected Nx3 point arrays, got {source.shape}"
        )

    if len(source) < 3:
        raise ValueError(
            "At least 3 corresponding points are required."
        )

    source_centroid = source.mean(axis=0)
    target_centroid = target.mean(axis=0)

    source_centered = source - source_centroid
    target_centered = target - target_centroid

    H = source_centered.T @ target_centered

    U, _, Vt = np.linalg.svd(H)

    R = Vt.T @ U.T

    # Prevent reflection.
    if np.linalg.det(R) < 0:
        Vt[-1, :] *= -1
        R = Vt.T @ U.T

    T = target_centroid.reshape(3, 1) - R @ source_centroid.reshape(3, 1)

    transformed = (
        R @ source.T + T
    ).T

    errors = np.linalg.norm(
        transformed - target,
        axis=1,
    )

    rms = float(np.sqrt(np.mean(errors**2)))

    return R, T, rms


# =====================================================================
# STAGE 5 - Transform utilities
# =====================================================================


def invert_rigid_transform(
    R: np.ndarray,
    T: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Invert:

        P_target = R @ P_source + T

    to:

        P_source = R_inv @ P_target + T_inv
    """
    R_inv = R.T
    T_inv = -R_inv @ T

    return R_inv, T_inv


def transform_points(
    points: np.ndarray,
    R: np.ndarray,
    T: np.ndarray,
) -> np.ndarray:
    """Apply P_target = R @ P_source + T to Nx3 points."""
    points = np.asarray(points, dtype=np.float64)

    return (
        R @ points.T + T
    ).T


# =====================================================================
# STAGE 6 - Main
# =====================================================================


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )

    parser.add_argument(
        "img_points_npz",
        type=Path,
        help="Output of stereo/build_stereo_points.py",
    )

    parser.add_argument(
        "cam1_intrinsics_json",
        type=Path,
        help="Camera 1 intrinsic calibration JSON",
    )

    parser.add_argument(
        "cam2_intrinsics_json",
        type=Path,
        help="Camera 2 intrinsic calibration JSON",
    )

    parser.add_argument(
        "stereo_calibration_json",
        type=Path,
        help="Output of stereo_calibrate.py",
    )

    parser.add_argument(
        "--spacing-x",
        type=float,
        default=1.0,
        help="LED spacing in global X direction.",
    )

    parser.add_argument(
        "--spacing-y",
        type=float,
        default=1.0,
        help="LED spacing in global Y direction.",
    )

    parser.add_argument(
        "--columns",
        type=int,
        default=4,
        help="Number of LED columns.",
    )

    parser.add_argument(
        "--rows",
        type=int,
        default=6,
        help="Number of LED rows.",
    )

    parser.add_argument(
        "--h5-id-for-led1",
        type=int,
        default=0,
        help="Beacon ID assigned to the first LED.",
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=Path(
            "track_logs/stereo/global_frame_calibration.json"
        ),
    )

    parser.add_argument(
        "--max-duration-s",
        type=float,
        default=None,
        help=(
            "Use only the first N seconds of stereo views (by sample_times_cam1 "
            "in img_points_npz, relative to the first view), instead of every "
            "view build_stereo_points.py produced. The board-on-floor recording "
            "is stationary, so a short window is normally enough data - this "
            "bounds THIS script's own compute and gives a fixed-size, "
            "reproducible fit regardless of how long the recording ran. Does "
            "NOT reduce upstream tracking/decoding time for the raw recording "
            "(that already processed the whole file before this script ever "
            "runs) - trim the raw .es file itself if that's what you need. "
            "Leave unset to use every view (previous behavior)."
        ),
    )

    args = parser.parse_args()

    # ---------------------------------------------------------------
    # Load stereo image points
    # ---------------------------------------------------------------

    npz = np.load(args.img_points_npz)

    img_points_cam1 = np.asarray(
        npz["img_points_cam1"],
        dtype=np.float64,
    )

    img_points_cam2 = np.asarray(
        npz["img_points_cam2"],
        dtype=np.float64,
    )

    beacon_ids = np.asarray(
        npz["beacon_ids"],
    ).tolist()

    if args.max_duration_s is not None:
        if "sample_times_cam1" not in npz:
            parser.error(
                f"--max-duration-s was passed but {args.img_points_npz} has no "
                "'sample_times_cam1' array (built by an older, incompatible "
                "stereo/build_stereo_points.py?) - can't filter by time without it."
            )
        sample_times = np.asarray(npz["sample_times_cam1"], dtype=np.float64)
        if sample_times.shape[0] != img_points_cam1.shape[0]:
            parser.error(
                f"sample_times_cam1 has {sample_times.shape[0]} entries but "
                f"img_points_cam1 has {img_points_cam1.shape[0]} views - "
                f"{args.img_points_npz} looks corrupted or from an incompatible "
                "build_stereo_points.py version."
            )
        # Relative to the first kept view's own timestamp, not to 0 - sample
        # timestamps are on cam1's own clock, whatever its epoch/origin is.
        t0 = float(sample_times[0])
        mask = (sample_times - t0) <= args.max_duration_s
        n_total = mask.shape[0]
        n_kept = int(mask.sum())
        if n_kept == 0:
            parser.error(
                f"--max-duration-s {args.max_duration_s:.3f} left 0 of {n_total} "
                "views - the window is shorter than the gap between consecutive "
                "samples (see build_stereo_points.py's --hz), or sample_times_cam1 "
                "isn't sorted ascending. Increase --max-duration-s."
            )
        img_points_cam1 = img_points_cam1[mask]
        img_points_cam2 = img_points_cam2[mask]
        actual_span_s = float(sample_times[mask][-1] - t0)
        print(
            f"--max-duration-s {args.max_duration_s:.3f}: using {n_kept}/{n_total} "
            f"views (first {actual_span_s:.3f}s of the recording)."
        )

    if img_points_cam1.shape != img_points_cam2.shape:
        raise ValueError(
            "Camera 1 and Camera 2 image-point arrays have different shapes: "
            f"{img_points_cam1.shape} vs {img_points_cam2.shape}"
        )

    if img_points_cam1.ndim != 3 or img_points_cam1.shape[2] != 2:
        raise ValueError(
            "Expected image points with shape "
            "(num_views, num_beacons, 2)."
        )

    num_views = img_points_cam1.shape[0]
    num_beacons = img_points_cam1.shape[1]

    if len(beacon_ids) != num_beacons:
        raise ValueError(
            f"Number of beacon IDs ({len(beacon_ids)}) does not match "
            f"points per view ({num_beacons})."
        )

    # ---------------------------------------------------------------
    # Load intrinsics
    # ---------------------------------------------------------------

    cam1_matrix, cam1_dist, image_size1 = load_intrinsics(
        args.cam1_intrinsics_json
    )

    cam2_matrix, cam2_dist, image_size2 = load_intrinsics(
        args.cam2_intrinsics_json
    )

    if image_size1 != image_size2:
        raise ValueError(
            f"Camera image sizes differ: "
            f"{image_size1} vs {image_size2}"
        )

    # ---------------------------------------------------------------
    # Load stereo extrinsics
    # ---------------------------------------------------------------

    stereo = load_stereo_calibration(
        args.stereo_calibration_json
    )

    R_stereo = stereo["R"]
    T_stereo = stereo["T"]

    # ---------------------------------------------------------------
    # LED geometry in global frame {0}
    # ---------------------------------------------------------------

    geometry = make_led_box_geometry(
        spacing_x=args.spacing_x,
        spacing_y=args.spacing_y,
        columns=args.columns,
        rows=args.rows,
        h5_id_for_led1=args.h5_id_for_led1,
    )

    missing = [
        beacon_id
        for beacon_id in beacon_ids
        if beacon_id not in geometry
    ]

    if missing:
        raise ValueError(
            f"Beacon IDs {missing} are missing from the LED geometry."
        )

    object_points_global = np.stack(
        [geometry[beacon_id] for beacon_id in beacon_ids]
    ).astype(np.float64)

    # ---------------------------------------------------------------
    # Projection matrices
    #
    # IMPORTANT:
    #
    # P1 = K1 [I | 0]
    # P2 = K2 [R | T]
    #
    # Therefore triangulated points are Camera 1 coordinates {A}.
    # ---------------------------------------------------------------

    P1, P2 = build_projection_matrices(
        cam1_matrix,
        cam2_matrix,
        R_stereo,
        T_stereo,
    )

    # ---------------------------------------------------------------
    # Triangulate every calibration view
    # ---------------------------------------------------------------

    camera_points_per_view: list[np.ndarray] = []

    for view_index in range(num_views):
        points_cam1 = triangulate_points(
            P1,
            P2,
            img_points_cam1[view_index],
            img_points_cam2[view_index],
        )

        camera_points_per_view.append(points_cam1)

    # ---------------------------------------------------------------
    # Estimate Camera 1 -> Global transform for each view.
    #
    # We have:
    #
    #   LED points in Global frame:
    #       P_0
    #
    #   Triangulated LED points in Camera 1 frame:
    #       P_A
    #
    # Estimate:
    #
    #   P_A = R_0_to_A @ P_0 + T_0_to_A
    #
    # Then invert it:
    #
    #   P_0 = R_A_to_0 @ P_A + T_A_to_0
    # ---------------------------------------------------------------

    per_view_results = []

    R_A_to_0_all = []
    T_A_to_0_all = []

    for view_index, points_camera in enumerate(
        camera_points_per_view
    ):
        R_0_to_A, T_0_to_A, rms = estimate_rigid_transform(
            object_points_global,
            points_camera,
        )

        R_A_to_0, T_A_to_0 = invert_rigid_transform(
            R_0_to_A,
            T_0_to_A,
        )

        R_A_to_0_all.append(R_A_to_0)
        T_A_to_0_all.append(T_A_to_0)

        per_view_results.append(
            {
                "view_index": view_index,
                "fit_rms": rms,
                "R_global_to_camera1": R_0_to_A.tolist(),
                "T_global_to_camera1": T_0_to_A.ravel().tolist(),
                "R_camera1_to_global": R_A_to_0.tolist(),
                "T_camera1_to_global": T_A_to_0.ravel().tolist(),
            }
        )

    # ---------------------------------------------------------------
    # Use the first calibration view as the reference global transform.
    #
    # If the LED board remains physically fixed, all views should
    # produce approximately the same Camera1 -> Global transform.
    #
    # If the board moves between views, each view has its own pose and
    # cannot be collapsed into one static transform.
    # ---------------------------------------------------------------

    R_A_to_0_reference = R_A_to_0_all[0]
    T_A_to_0_reference = T_A_to_0_all[0]

    # ---------------------------------------------------------------
    # Evaluate consistency of all views relative to the first one.
    # ---------------------------------------------------------------

    transformed_per_view = []

    for points_camera in camera_points_per_view:
        points_global = transform_points(
            points_camera,
            R_A_to_0_reference,
            T_A_to_0_reference,
        )

        transformed_per_view.append(points_global)

    consistency_errors = []

    for points_global in transformed_per_view:
        errors = np.linalg.norm(
            points_global - object_points_global,
            axis=1,
        )

        consistency_errors.extend(errors.tolist())

    global_rms = float(
        np.sqrt(
            np.mean(
                np.asarray(consistency_errors) ** 2
            )
        )
    )

    # ---------------------------------------------------------------
    # Print results
    # ---------------------------------------------------------------

    print(f"Views: {num_views}")
    print(f"LEDs/view: {num_beacons}")

    print("\nStereo calibration:")
    print(f"R:\n{R_stereo}")
    print(f"T: {T_stereo.ravel()}")

    print("\nGlobal LED frame:")
    print("  Origin: first LED")
    print("  +X: increasing LED column")
    print("  +Y: increasing LED row")
    print("  Z: board normal")

    print("\nCamera 1 -> Global transform:")
    print(f"R_A_to_0:\n{R_A_to_0_reference}")
    print(f"T_A_to_0:\n{T_A_to_0_reference.ravel()}")

    print(
        "\nReference-view LED registration RMS: "
        f"{per_view_results[0]['fit_rms']:.4f}"
    )

    print(
        "All-view consistency RMS: "
        f"{global_rms:.4f}"
    )

    # ---------------------------------------------------------------
    # Save result
    # ---------------------------------------------------------------

    output = {
        "img_points_npz": str(args.img_points_npz),
        "cam1_intrinsics_json": str(args.cam1_intrinsics_json),
        "cam2_intrinsics_json": str(args.cam2_intrinsics_json),
        "stereo_calibration_json": str(
            args.stereo_calibration_json
        ),
        "coordinate_systems": {
            "global": "{0}",
            "camera": "{A}",
            "description": (
                "Global frame {0} is attached to the LED calibration board. "
                "Camera frame {A} is Camera 1."
            ),
        },
        "geometry": {
            "spacing_x": args.spacing_x,
            "spacing_y": args.spacing_y,
            "columns": args.columns,
            "rows": args.rows,
            "h5_id_for_led1": args.h5_id_for_led1,
        },
        "num_views": num_views,
        "beacon_ids": beacon_ids,
        "image_size": list(image_size1),
        "stereo": {
            "R_camera1_to_camera2": R_stereo.tolist(),
            "T_camera1_to_camera2": T_stereo.ravel().tolist(),
        },
        "global_transform": {
            "direction": "camera1_to_global",
            "formula": (
                "P_global = "
                "R_camera1_to_global @ P_camera1 "
                "+ T_camera1_to_global"
            ),
            "R": R_A_to_0_reference.tolist(),
            "T": T_A_to_0_reference.ravel().tolist(),
        },
        "reference_view": 0,
        "reference_view_registration_rms": float(
            per_view_results[0]["fit_rms"]
        ),
        "all_view_consistency_rms": global_rms,
        "per_view": per_view_results,
    }

    args.output.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    args.output.write_text(
        json.dumps(output, indent=2) + "\n"
    )

    print(f"\nSaved {args.output}")


if __name__ == "__main__":
    main()