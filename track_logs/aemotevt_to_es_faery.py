def read_aemotevt(path):
    print(f"[Info] Loading .aemotevt log from {path}...")

    with open(path, "rb") as f:
        header_bytes = f.read(AEMOTEVT_HEADER_SIZE)

        magic, version, _reserved, record_size, _reserved2 = struct.unpack(
            AEMOTEVT_HEADER_FMT,
            header_bytes
        )

        if magic != b"AEMOTEVT":
            raise ValueError(
                f"Unexpected magic bytes: {magic!r}"
            )

        if record_size != AEMOTEVT_RECORD_SIZE:
            raise ValueError(
                f"record_size mismatch: header says {record_size}, "
                f"this script expects {AEMOTEVT_RECORD_SIZE} "
                f"(version {version})."
            )

        # Read everything after the header.
        raw = f.read()

    # Check that the file contains complete records.
    if len(raw) % AEMOTEVT_RECORD_SIZE != 0:
        raise ValueError(
            f"Event data has {len(raw)} bytes, which is not "
            f"a multiple of {AEMOTEVT_RECORD_SIZE}."
        )

    events = np.frombuffer(
        raw,
        dtype=AEMOTEVT_DTYPE
    )

    return events


def write_es_dvs(events, output_path, width, height, count_threshold=10_000):
    """events: iterable of (t_seconds, x, y, p) in non-decreasing t order.
    Writes an Event Stream v2 dvs file to output_path."""

    print(f"[Info] Converting .aemotevt log to .es format, saving to {output_path}...")

    # Sort in order of ID's once so that we don't need to search the entire dataset every time
    order = np.argsort(events["track_id"], kind="stable")
    sorted_ids = events["track_id"][order]

    unique_ids, starts, counts = np.unique(
        sorted_ids,
        return_index=True,
        return_counts=True,
    )

    file_root, file_ext = os.path.splitext(output_path)

    for track_id, start, count in zip(unique_ids, starts, counts):
        if count < count_threshold: continue
        track = events[order[start:start + count]]

        print(track_id, count, np.unique(track["track_id"]))
        # Convert to Faery array
        faery_array = np.empty(len(track), dtype=faery.EVENTS_DTYPE)
        faery_array["t"] = (track["t"] * faery.s.microseconds).astype(np.uint64)
        faery_array["x"] = track["x"]
        faery_array["y"] = track["y"]
        faery_array["p"] = track["p"].astype(bool)

        output_path_i = f"{file_root}_{track_id}{file_ext}"
        # zero_t0=False: faery's default (True) normalizes each track's
        # timestamps to start near 0 and is supposed to store the original
        # offset in the file so it can be reconstructed later - but for
        # .es output specifically, faery's own docs say that offset "is
        # discarded if the file type is ES", so with the default there is
        # NO way to recover it, even in principle. track["t"] here is
        # already an absolute time (shared across the whole recording, not
        # per-track), so zero_t0=False just writes it through unchanged.
        # This matters most for a beacon that leaves and re-enters the
        # frame: AEMOT assigns it a NEW track_id on re-entry, and with the
        # old default that second track's timestamps would silently reset
        # to ~0 - making it look like it happened at the START of the
        # recording instead of wherever it actually re-appeared - which
        # then corrupts any downstream time-sync matching against it.
        faery.events_stream_from_array(faery_array, dimensions=(width,height)).to_file(
            output_path_i, zero_t0=False
        )
    return


